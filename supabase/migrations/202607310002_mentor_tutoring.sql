begin;

create table if not exists public.mentor_profiles (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid unique references public.profiles(id) on delete set null,
  display_name text not null check (char_length(display_name) between 2 and 40),
  headline text not null default '',
  bio text not null default '',
  avatar_url text,
  specialties text[] not null default '{}',
  credentials text[] not null default '{}',
  languages text[] not null default array['中文']::text[],
  verification_label text not null default '平台认证老师',
  active boolean not null default false,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mentor_offers (
  id uuid primary key default gen_random_uuid(),
  mentor_id uuid not null references public.mentor_profiles(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 80),
  description text not null default '',
  price_cents integer not null check (price_cents >= 0),
  currency text not null default 'CNY' check (char_length(currency) = 3),
  duration_days integer not null default 30 check (duration_days between 1 and 366),
  weekly_questions integer not null default 3 check (weekly_questions between 1 and 100),
  active boolean not null default true,
  sort_order integer not null default 100,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mentor_orders (
  id uuid primary key default gen_random_uuid(),
  buyer_id uuid not null references public.profiles(id) on delete restrict,
  mentor_id uuid not null references public.mentor_profiles(id) on delete restrict,
  offer_id uuid not null references public.mentor_offers(id) on delete restrict,
  amount_cents integer not null check (amount_cents >= 0),
  currency text not null check (char_length(currency) = 3),
  status text not null default 'pending'
    check (status in ('pending', 'paid', 'cancelled', 'refunded', 'failed')),
  payment_provider text,
  provider_order_id text,
  idempotency_key uuid not null default gen_random_uuid(),
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (payment_provider, provider_order_id),
  unique (idempotency_key)
);

create table if not exists public.mentor_entitlements (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null unique references public.mentor_orders(id) on delete restrict,
  student_id uuid not null references public.profiles(id) on delete restrict,
  mentor_id uuid not null references public.mentor_profiles(id) on delete restrict,
  weekly_question_limit integer not null check (weekly_question_limit between 1 and 100),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status text not null default 'active'
    check (status in ('active', 'expired', 'revoked', 'refunded')),
  created_at timestamptz not null default now()
);

create table if not exists public.mentor_payment_events (
  event_id text primary key,
  provider text not null,
  event_type text not null,
  order_id uuid references public.mentor_orders(id) on delete set null,
  received_at timestamptz not null default now()
);

create table if not exists public.mentor_threads (
  id uuid primary key default gen_random_uuid(),
  entitlement_id uuid not null unique references public.mentor_entitlements(id) on delete restrict,
  student_id uuid not null references public.profiles(id) on delete restrict,
  mentor_id uuid not null references public.mentor_profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.mentor_messages (
  id bigint generated by default as identity primary key,
  thread_id uuid not null references public.mentor_threads(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete restrict,
  body text not null check (char_length(body) between 1 and 5000),
  message_kind text not null check (message_kind in ('question', 'reply', 'system')),
  counts_quota boolean not null default false,
  quota_week date,
  created_at timestamptz not null default now()
);

create index if not exists mentor_profiles_catalog_idx
  on public.mentor_profiles(active, sort_order, created_at);
create index if not exists mentor_offers_catalog_idx
  on public.mentor_offers(mentor_id, active, sort_order);
create index if not exists mentor_orders_buyer_idx
  on public.mentor_orders(buyer_id, created_at desc);
create index if not exists mentor_entitlements_student_idx
  on public.mentor_entitlements(student_id, status, ends_at);
create index if not exists mentor_messages_thread_idx
  on public.mentor_messages(thread_id, created_at);
create index if not exists mentor_messages_quota_idx
  on public.mentor_messages(thread_id, quota_week)
  where counts_quota = true;

create or replace function public.mentor_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid()
      and role = 'admin'
  );
$$;

revoke all on function public.mentor_is_admin() from public;
grant execute on function public.mentor_is_admin() to authenticated;

alter table public.mentor_profiles enable row level security;
alter table public.mentor_offers enable row level security;
alter table public.mentor_orders enable row level security;
alter table public.mentor_entitlements enable row level security;
alter table public.mentor_payment_events enable row level security;
alter table public.mentor_threads enable row level security;
alter table public.mentor_messages enable row level security;

