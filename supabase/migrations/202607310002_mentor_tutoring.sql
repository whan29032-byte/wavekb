create or replace function public.create_mentor_order(p_offer_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_offer public.mentor_offers%rowtype;
  new_order_id uuid;
begin
  if auth.uid() is null then
    raise exception 'authentication_required';
  end if;
  select *
  into selected_offer
  from public.mentor_offers
  where id = p_offer_id
    and active;
  if selected_offer.id is null then
    raise exception 'offer_unavailable';
  end if;
  if not exists (
    select 1 from public.mentor_profiles
    where id = selected_offer.mentor_id
      and active
  ) then
    raise exception 'mentor_unavailable';
  end if;
  insert into public.mentor_orders (
    buyer_id,
    mentor_id,
    offer_id,
    amount_cents,
    currency
  )
  values (
    auth.uid(),
    selected_offer.mentor_id,
    selected_offer.id,
    selected_offer.price_cents,
    upper(selected_offer.currency)
  )
  returning id into new_order_id;
  return new_order_id;
end;
$$;

revoke all on function public.create_mentor_order(uuid) from public;
grant execute on function public.create_mentor_order(uuid) to authenticated;

create or replace function public.activate_paid_mentor_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_offer public.mentor_offers%rowtype;
  entitlement_id uuid;
begin
  if new.status = 'paid' and old.status is distinct from 'paid' then
    select * into selected_offer
    from public.mentor_offers
    where id = new.offer_id;

    insert into public.mentor_entitlements (
      order_id,
      student_id,
      mentor_id,
      weekly_question_limit,
      starts_at,
      ends_at,
      status
    )
    values (
      new.id,
      new.buyer_id,
      new.mentor_id,
      selected_offer.weekly_questions,
      coalesce(new.paid_at, now()),
      coalesce(new.paid_at, now()) + make_interval(days => selected_offer.duration_days),
      'active'
    )
    on conflict (order_id) do update set
      status = 'active',
      starts_at = excluded.starts_at,
      ends_at = excluded.ends_at
    returning id into entitlement_id;

    insert into public.mentor_threads (
      entitlement_id,
      student_id,
      mentor_id
    )
    values (entitlement_id, new.buyer_id, new.mentor_id)
    on conflict (entitlement_id) do nothing;
  elsif new.status in ('refunded', 'cancelled') and old.status = 'paid' then
    update public.mentor_entitlements
    set status = case when new.status = 'refunded' then 'refunded' else 'revoked' end
    where order_id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists mentor_orders_activate_after_payment on public.mentor_orders;
create trigger mentor_orders_activate_after_payment
after update of status on public.mentor_orders
for each row
execute function public.activate_paid_mentor_order();

create or replace function public.list_my_mentor_access()
returns table (
  entitlement_id uuid,
  mentor_id uuid,
  mentor_name text,
  mentor_avatar_url text,
  thread_id uuid,
  status text,
  weekly_question_limit integer,
  questions_used bigint,
  starts_at timestamptz,
  ends_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    e.id,
    e.mentor_id,
    m.display_name,
    m.avatar_url,
    t.id,
    case
      when e.status = 'active' and e.ends_at > now() then 'active'
      when e.status = 'active' then 'expired'
      else e.status
    end,
    e.weekly_question_limit,
    (
      select count(*)
      from public.mentor_messages message
      where message.thread_id = t.id
        and message.counts_quota
        and message.quota_week = date_trunc('week', now())::date
    ),
    e.starts_at,
    e.ends_at
  from public.mentor_entitlements e
  join public.mentor_profiles m on m.id = e.mentor_id
  join public.mentor_threads t on t.entitlement_id = e.id
  where e.student_id = auth.uid()
  order by e.created_at desc;
$$;

create or replace function public.get_mentor_thread(p_thread_id uuid)
returns table (
  thread_id uuid,
  mentor_id uuid,
  mentor_name text,
  mentor_avatar_url text,
  student_id uuid,
  status text,
  weekly_question_limit integer,
  questions_used bigint,
  starts_at timestamptz,
  ends_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select
    t.id,
    t.mentor_id,
    m.display_name,
    m.avatar_url,
    t.student_id,
    case
      when e.status = 'active' and e.ends_at > now() then 'active'
      when e.status = 'active' then 'expired'
      else e.status
    end,
    e.weekly_question_limit,
    (
      select count(*)
      from public.mentor_messages message
      where message.thread_id = t.id
        and message.counts_quota
        and message.quota_week = date_trunc('week', now())::date
    ),
    e.starts_at,
    e.ends_at
  from public.mentor_threads t
  join public.mentor_entitlements e on e.id = t.entitlement_id
  join public.mentor_profiles m on m.id = t.mentor_id
  where t.id = p_thread_id
    and (
      t.student_id = auth.uid()
      or m.owner_id = auth.uid()
      or public.mentor_is_admin()
    );
$$;

create or replace function public.list_mentor_messages(p_thread_id uuid)
returns table (
  id bigint,
  sender_id uuid,
  body text,
  message_kind text,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select message.id, message.sender_id, message.body, message.message_kind, message.created_at
  from public.mentor_messages message
  where message.thread_id = p_thread_id
    and exists (
      select 1
      from public.mentor_threads t
      join public.mentor_profiles m on m.id = t.mentor_id
      where t.id = p_thread_id
        and (
          t.student_id = auth.uid()
          or m.owner_id = auth.uid()
          or public.mentor_is_admin()
        )
    )
  order by message.created_at;
$$;

create or replace function public.send_mentor_message(
  p_thread_id uuid,
  p_body text
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  selected_thread public.mentor_threads%rowtype;
  selected_entitlement public.mentor_entitlements%rowtype;
  selected_mentor public.mentor_profiles%rowtype;
  is_student boolean;
  used_count bigint;
  new_message_id bigint;
  clean_body text := btrim(coalesce(p_body, ''));
begin
  if auth.uid() is null then
    raise exception 'authentication_required';
  end if;
  if char_length(clean_body) < 5 or char_length(clean_body) > 5000 then
    raise exception 'invalid_message';
  end if;

  select * into selected_thread
  from public.mentor_threads
  where id = p_thread_id;
  select * into selected_entitlement
  from public.mentor_entitlements
  where id = selected_thread.entitlement_id;
  select * into selected_mentor
  from public.mentor_profiles
  where id = selected_thread.mentor_id;

  is_student := selected_thread.student_id = auth.uid();
  if not is_student
    and selected_mentor.owner_id is distinct from auth.uid()
    and not public.mentor_is_admin() then
    raise exception 'thread_access_denied';
  end if;

  if is_student then
    if selected_entitlement.status <> 'active'
      or selected_entitlement.ends_at <= now() then
      raise exception 'tutoring_access_expired';
    end if;
    select count(*) into used_count
    from public.mentor_messages
    where thread_id = p_thread_id
      and counts_quota
      and quota_week = date_trunc('week', now())::date;
    if used_count >= selected_entitlement.weekly_question_limit then
      raise exception 'weekly_question_limit_reached';
    end if;
  end if;

  insert into public.mentor_messages (
    thread_id,
    sender_id,
    body,
    message_kind,
    counts_quota,
    quota_week
  )
  values (
    p_thread_id,
    auth.uid(),
    clean_body,
    case when is_student then 'question' else 'reply' end,
    is_student,
    case when is_student then date_trunc('week', now())::date else null end
  )
  returning id into new_message_id;

  update public.mentor_threads
  set updated_at = now()
  where id = p_thread_id;

  return new_message_id;
end;
$$;

