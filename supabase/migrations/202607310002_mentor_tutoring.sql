  or exists (
    select 1 from public.mentor_profiles
    where mentor_profiles.id = mentor_entitlements.mentor_id
      and mentor_profiles.owner_id = auth.uid()
  )
  or public.mentor_is_admin()
);

drop policy if exists mentor_payment_events_admin_read on public.mentor_payment_events;
create policy mentor_payment_events_admin_read
on public.mentor_payment_events
for select
to authenticated
using (public.mentor_is_admin());

drop policy if exists mentor_threads_participant_read on public.mentor_threads;
create policy mentor_threads_participant_read
on public.mentor_threads
for select
to authenticated
using (
  student_id = auth.uid()
  or exists (
    select 1 from public.mentor_profiles
    where mentor_profiles.id = mentor_threads.mentor_id
      and mentor_profiles.owner_id = auth.uid()
  )
  or public.mentor_is_admin()
);

drop policy if exists mentor_messages_participant_read on public.mentor_messages;
create policy mentor_messages_participant_read
on public.mentor_messages
for select
to authenticated
using (
  exists (
    select 1
    from public.mentor_threads
    left join public.mentor_profiles
      on mentor_profiles.id = mentor_threads.mentor_id
    where mentor_threads.id = mentor_messages.thread_id
      and (
        mentor_threads.student_id = auth.uid()
        or mentor_profiles.owner_id = auth.uid()
        or public.mentor_is_admin()
      )
  )
);

create or replace function public.list_mentor_catalog()
returns table (
  mentor_id uuid,
  display_name text,
  headline text,
  bio text,
  avatar_url text,
  specialties text[],
  credentials text[],
  languages text[],
  verification_label text,
  offers jsonb
)
language sql
stable
security definer
set search_path = public
as $$
  select
    m.id,
    m.display_name,
    m.headline,
    m.bio,
    m.avatar_url,
    m.specialties,
    m.credentials,
    m.languages,
    m.verification_label,
    coalesce(
      jsonb_agg(
        jsonb_build_object(
          'id', o.id,
          'name', o.name,
          'description', o.description,
          'price_cents', o.price_cents,
          'currency', o.currency,
          'duration_days', o.duration_days,
          'weekly_questions', o.weekly_questions,
          'active', o.active
        )
        order by o.sort_order, o.created_at
      ) filter (where o.id is not null and o.active),
      '[]'::jsonb
    )
  from public.mentor_profiles m
  left join public.mentor_offers o on o.mentor_id = m.id
  where m.active
  group by m.id
  order by m.sort_order, m.created_at;
$$;

